"""Write every table to outputs/tables and a numbers-first findings summary to
outputs/findings.md. All figures in the summary are computed here, so re-running
the pipeline on refreshed data refreshes the write-up."""
from pathlib import Path

import pandas as pd

from .stats import kruskal, summarise


def _gbp(x: float) -> str:
    return f"£{x / 1e6:,.2f}m" if abs(x) >= 1e6 else f"£{x / 1e3:,.0f}k"


def _pct(x: float, dp: int = 1) -> str:
    return f"{x * 100:.{dp}f}%"


def save_tables(results: dict, out: Path) -> None:
    tdir = out / "tables"
    tdir.mkdir(parents=True, exist_ok=True)
    for area, r in results.items():
        if isinstance(r, pd.DataFrame):
            r.to_csv(tdir / f"{area}.csv", index=False)
            continue
        for k, v in r.items():
            if isinstance(v, (pd.DataFrame, pd.Series)):
                v.to_csv(tdir / f"{area}__{k}.csv")


def impact_ranking(S: dict, L: dict, Z: dict, m: pd.DataFrame) -> pd.DataFrame:
    """Order findings by annual £ at stake for the two decisions."""
    sc = S["scorecard"]
    est_median = sc["margin_24m"].median()
    lon = sc[sc["region"] == "London"]
    london_gap = lon["revenue_24m"].sum() / 2 * (est_median - lon["net_profit_24m"].sum() / lon["revenue_24m"].sum())
    econ = L["economics"].loc[2024]
    d = Z["_daily"]
    wk = d.groupby("is_weekend").agg(rev=("total_revenue_gbp", "sum"), hrs=("total_staff_hours", "sum"))
    weekend_hours_share = wk.loc[True, "hrs"] / wk["hrs"].sum()
    productivity_gap = 1 - (wk.loc[True, "rev"] / wk.loc[True, "hrs"]) / (wk.loc[False, "rev"] / wk.loc[False, "hrs"])
    staffing_year = m[m["year"] == 2024]["monthly_staffing_cost_gbp"].sum()
    weekend_saving = staffing_year * weekend_hours_share * productivity_gap
    q1, q4 = S["rent"]["rent_band_table"]["median"].iloc[[0, -1]]
    loss_stores = sc[sc["net_profit_24m"] < 0]
    rows = [
        ("Expansion", "London City-Centre stores earn half the estate margin; rent is ~20% of their revenue",
         london_gap, "Gap if London earned the estate median margin, per year", "High"),
        ("Loyalty", "Redemption costs ~10% of net profit with no measurable incremental spend",
         econ["redemption_cost"], "Annual redemption cost at risk (2024)", "High that no uplift is visible; Medium that none exists"),
        ("Loyalty", "Break-even needs members to spend ~10% more than they otherwise would",
         econ["breakeven_incremental_revenue"], "Incremental revenue needed per year to cover redemption", "High (arithmetic)"),
        ("Staffing", "Weekend revenue ~24% below weekdays but labour hours are flat",
         weekend_saving, "Upper-bound saving if weekend hours matched weekday productivity", "Medium (daily sample, hours not costed)"),
        ("Expansion", "Rent does not buy revenue; each rent quartile up costs ~2-3 margin points",
         (q1 - q4) * sc["revenue_24m"].median() / 2, "Profit gap per store per year, lowest vs highest rent quartile", "Medium-High"),
        ("Review", f"Stores flagged for review: {len(S['review'])}; {len(loss_stores)} loss-making over 24 months",
         -loss_stores["net_profit_24m"].sum() / 2, "Annual loss removed by exiting loss-making stores (before exit costs)", "High for ranking, Low for 2023-24 change"),
        ("Product", "Revenue mix is flat and realised margin is ~62% in every stream",
         0.0, "No mix lever visible in this data", "Medium"),
        ("Staffing", "No repeatable monthly seasonality; day-of-week is the only reliable pattern",
         0.0, "Plan rotas by weekday, not by month", "High for day-of-week; High that months do not repeat"),
    ]
    out = pd.DataFrame(rows, columns=["decision", "finding", "gbp_per_year", "what_the_number_is", "confidence"])
    return out.sort_values("gbp_per_year", ascending=False, kind="stable").reset_index(drop=True)


def findings_md(t: dict, P: pd.DataFrame, S: dict, L: dict, Z: dict, X: dict, R: pd.DataFrame,
                m: pd.DataFrame) -> str:
    sc = S["scorecard"]
    econ = L["economics"]
    lines = ["# Sunrise Coffee Chain: findings for the CCO (2023-2024)", "",
             "Generated by `run_analysis.py`. P&L figures come from `fact_store_monthly_profitability` only. "
             "`fact_daily_sales` is a ~20% sample and is used only for shares, ratios and within-store comparisons. "
             "Medians are shown with means; groups with fewer than 5 stores or 30 rows are flagged **small sample**.", ""]

    lines += ["## 1. Data quality", "",
              f"{(P['severity'] == 'High').sum()} high, {(P['severity'] == 'Medium').sum()} medium and "
              f"{(P['severity'] == 'Low').sum()} low severity issues. Full list in `outputs/data_quality.md`.", ""]
    for _, r in P[P["severity"] == "High"].iterrows():
        lines.append(f"- **{r['check']}** ({r['table']}): {r['data_shows']}")
    lines.append("")

    pers = S["persistence"]
    sp = S["np_change_spread"]
    lines += ["## 2. Store, format and region", "",
              f"- Estate: revenue {_gbp(econ.loc[2023, 'revenue'])} (2023) vs {_gbp(econ.loc[2024, 'revenue'])} (2024); "
              f"net profit {_gbp(econ.loc[2023, 'net_profit'])} vs {_gbp(econ.loc[2024, 'net_profit'])}.",
              f"- Store 24-month margin: median {_pct(sc['margin_24m'].median())}, mean {_pct(sc['margin_24m'].mean())}, "
              f"range {_pct(sc['margin_24m'].min())} to {_pct(sc['margin_24m'].max())}.",
              f"- Store margins are persistent: 2023 vs 2024 rank correlation rho={pers['margin_2023_vs_2024_spearman']:.2f}. "
              f"But only {_pct(pers['share_of_margin_variance_between_stores'], 0)} of month-to-month margin variance is between stores.",
              f"- 2023 to 2024 profit changes per store have std {_gbp(sp['std'])}, versus {_gbp(sp['std_if_pure_noise'])} "
              f"expected from shuffling months at random: the 'improvers' and 'decliners' lists are indistinguishable from noise.", ""]
    for by in ["store_format", "location_type", "region"]:
        tb = S[by][["n_stores", "median_store_margin", "mean_store_margin", "median_np_per_store_per_year",
                    "median_rent_pct_revenue", "loss_month_share_doc", "loss_month_share_label", "small_sample"]]
        kw = S[f"{by}_kruskal"]
        lines += [f"### By {by.replace('_', ' ')} (Kruskal-Wallis p={kw['p']:.3f})", "", tb.to_markdown(floatfmt=".3f"), ""]
    ex = sc[sc["region"] != "London"]
    kwr, kwl = kruskal(ex, "region", "margin_24m"), kruskal(ex, "location_type", "margin_24m")
    cc = summarise(ex, "location_type", "margin_24m", min_rows=0)
    lines += [f"- Excluding London, regional differences are not significant (p={kwr['p']:.2f}) and nor are location types "
              f"(p={kwl['p']:.2f}; City-Centre ex-London median {_pct(cc.loc['City-Centre', 'median'])}). "
              "London is the one robust geographic signal.", ""]
    rent = S["rent"]
    lines += ["### Rent", "",
              f"- Rent vs revenue across stores: r={rent['rent_vs_revenue_all']['pearson_r']:.2f} "
              f"(p={rent['rent_vs_revenue_all']['pearson_p']:.2f}): higher rent does not bring higher revenue.",
              f"- Rent vs margin: r={rent['rent_vs_margin_all']['pearson_r']:.2f} (p={rent['rent_vs_margin_all']['pearson_p']:.3f}).", "",
              rent["rent_band_table"].to_markdown(floatfmt=".3f"), "",
              "### Stores to review", "", S["review"].to_markdown(index=False, floatfmt=".3f"), "",
              "### Biggest 2023-to-2024 profit changes (treat as noise, see above)", "",
              S["improvers"].to_markdown(index=False, floatfmt=",.0f"), "", S["decliners"].to_markdown(index=False, floatfmt=",.0f"), ""]

    a = L["atv"]
    lines += ["## 3. Loyalty programme", "",
              econ[["member_revenue", "redemption_cost", "gross_margin", "redemption_pct_member_revenue",
                    "redemption_pct_net_profit", "breakeven_incremental_revenue",
                    "breakeven_uplift_on_member_spend", "naive_net_value_brief"]].T.to_markdown(floatfmt=",.3f"), "",
              f"- Adoption vs member revenue share: r={L['adoption_vs_member_rev_pct']['pearson_r']:.3f} (n=60). Strong, but it is close to an identity.",
              f"- Member spend index (member revenue share / adoption rate): median {L['spend_index_summary']['50%']:.3f}, "
              f"mean {L['spend_index_summary']['mean']:.3f}. 1.0 means members spend the same as non-members.",
              f"- Revenue per transaction from the daily sample (within store): member £{a['within_store'].loc['loyalty_transactions', 'coef']:.2f} "
              f"(95% CI {a['within_store'].loc['loyalty_transactions', 'ci_low']:.2f}-{a['within_store'].loc['loyalty_transactions', 'ci_high']:.2f}) "
              f"vs non-member £{a['within_store'].loc['non_member_tx', 'coef']:.2f} "
              f"({a['within_store'].loc['non_member_tx', 'ci_low']:.2f}-{a['within_store'].loc['non_member_tx', 'ci_high']:.2f}). "
              f"Pooled: £{a['pooled'].loc['loyalty_transactions', 'coef']:.2f} vs £{a['pooled'].loc['non_member_tx', 'coef']:.2f}.",
              f"- ATV vs loyalty share of transactions: r={a['atv_vs_loyalty_tx_share']['pearson_r']:.3f} (n={a['atv_vs_loyalty_tx_share']['n']:,}).",
              f"- Adoption vs store revenue r={L['adoption_vs_monthly_revenue']['pearson_r']:.3f}; vs margin r={L['adoption_vs_margin']['pearson_r']:.3f}. "
              f"OLS: +10pts adoption -> {L['revenue_on_adoption_ols'].loc['loyalty_adoption_rate', 'coef'] / 10:+,.0f} GBP monthly revenue "
              f"(95% CI {L['revenue_on_adoption_ols'].loc['loyalty_adoption_rate', 'ci_low'] / 10:,.0f} to "
              f"{L['revenue_on_adoption_ols'].loc['loyalty_adoption_rate', 'ci_high'] / 10:,.0f}).",
              f"- Redemption cost per store is nearly flat (median {_gbp(L['stores']['redemption_per_year'].median())}/yr) "
              f"regardless of adoption (r={L['stores'][['loyalty_adoption_rate', 'redemption_per_year']].corr().iloc[0, 1]:.2f}).", ""]
    for by in ["store_format", "region"]:
        lines += [f"### Loyalty by {by.replace('_', ' ')} (adoption Kruskal p={L[f'{by}_kruskal_adoption']['p']:.2f}; "
                  f"spend index p={L[f'{by}_kruskal_index']['p']:.2f})", "",
                  L[by].drop(columns=["n_rows", "std"]).to_markdown(floatfmt=".3f"), ""]

    lines += ["## 4. Revenue mix and products", "", "### Shares (daily sample, store-days)", "",
              X["overall"].drop(columns=["group"]).to_markdown(index=False, floatfmt=".3f"), "",
              "### Share trend, pts per year, within store", "", X["trends"].to_markdown(index=False, floatfmt=".3f"), "",
              "### Margin by category: catalogue (dim_product) vs realised (daily GP regressed on stream revenue)", "",
              X["category_margins"].to_markdown(floatfmt=".3f"), "",
              "### Mix by format", "", X["by_format"].to_markdown(index=False, floatfmt=".3f"), ""]

    lines += ["## 5. Seasonality and staffing", "", "### Day of week (revenue index vs the store's own average)", "",
              Z["dow"].to_markdown(floatfmt=".3f"), "", "### Weekend vs weekday by format", "",
              Z["weekend_by_format"].to_markdown(floatfmt=".3f"), "",
              "### Bank holidays by format (England and Wales stores only)", "",
              Z["bank_holiday_by_format"].to_markdown(floatfmt=".3f"), "",
              "### Trading calendar", "", Z["calendar"].to_markdown(floatfmt=".3f"), "",
              f"- Staff hours vs revenue within store: r={Z['staff_hours_vs_revenue_within_store']['pearson_r']:.3f}. "
              f"Monthly staffing cost vs revenue within store: r={Z['staffing_vs_revenue_within_store']['pearson_r']:.3f}.",
              f"- Estate monthly revenue moves only {_pct(Z['estate_month_range_pct'])} from lowest to highest month. "
              f"2023 vs 2024 monthly profit pattern: r={Z['yoy_month_pattern']['pearson_r']:.2f} (p={Z['yoy_month_pattern']['pearson_p']:.2f}).", "",
              "### Net profit by month (estate, monthly table)", "", Z["np_pivot"].to_markdown(floatfmt=",.0f"), "",
              "### Quarters", "", Z["quarters"].to_markdown(index=False, floatfmt=",.0f"), "",
              "### Seasonal index by format", "", Z["format_quarter_index"].to_markdown(floatfmt=".3f"), ""]

    lines += ["## 6. Findings ranked by annual £ at stake", "", R.to_markdown(index=False, floatfmt=",.0f"), ""]
    return "\n".join(lines)


def data_quality_md(P: pd.DataFrame) -> str:
    return "# Data quality and brief mismatches\n\n" + P.to_markdown(index=False) + "\n"
